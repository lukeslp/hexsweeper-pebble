// Luke Steuber. Export the canonical Goldberg sphere as fixed native data.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const source = path.resolve(__dirname, '../../../../sphere/hexasphere.js');
const {generateHexasphere} = require(source);
const {tiles} = generateHexasphere(1, 2);
if (tiles.length !== 42 || tiles.filter(t => t.isPentagon).length !== 12) throw Error('Topology changed');
const vec = v => `{${[v.x,v.y,v.z].map(x => Math.round(x*32767)).join(',')}}`;
const lines = tiles.map(t => {
  const n=t.neighborIndices;
  if(n.length !== (t.isPentagon?5:6) || n.some(i=>!tiles[i].neighborIndices.includes(t.index))) throw Error('Adjacency');
  return `  {${n.length}, {${[...n,...Array(6-n.length).fill(0)].join(',')}}, ${vec(t.centerPoint)}, {${[...t.boundary.map(vec),...Array(6-t.boundary.length).fill('{0,0,0}')].join(',')}}}`;
});
const text=`// Generated by tools/geometry.cjs from sphere/hexasphere.js. Luke Steuber.\n// Source SHA-256: ${crypto.createHash('sha256').update(fs.readFileSync(source)).digest('hex')}\n#ifndef HS_GEOMETRY_H\n#define HS_GEOMETRY_H\n#include <stdint.h>\ntypedef struct {int16_t x,y,z;} MeshPoint;\ntypedef struct {uint8_t degree, neighbors[6]; MeshPoint center, boundary[6];} MeshCell;\nstatic const MeshCell HS_MESH[42] = {\n${lines.join(',\n')}\n};\n#endif\n`;
const output=path.resolve(__dirname,'../src/c/geometry.h');
if(process.argv.includes('--check')) {
  if(fs.readFileSync(output,'utf8')!==text) throw Error('Generated mesh drift');
} else fs.writeFileSync(output,text);
console.log('42 cells, 12 pentagons, symmetric adjacency; mesh '+(process.argv.includes('--check')?'verified':'generated'));
